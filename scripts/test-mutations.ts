async function testImages() {
  const sharp = (await import('sharp')).default;
  const base = () => sharp({ create: { width: 1200, height: 800, channels: 3, background: '#3a6' } });
  return {
    landscape: await base().jpeg().toBuffer(),
    // Stored landscape, displayed portrait.
    rotated: await base().jpeg().withMetadata({ orientation: 6 }).toBuffer(),
    notAnImage: Buffer.from('definitely not an image'),
  };
}

async function reserveAndPut(adminToken: string, body: Buffer, input: Record<string, unknown> = {}) {
  const reserved = (
    await ok(RESERVE, { input: { contentType: 'image/jpeg', byteSize: body.byteLength, keywords: [UPLOAD_KEYWORD], ...input } }, adminToken)
  ).dmbkPhotosReservePhotoUpload;
  const put = await fetch(reserved.uploadUrl, { method: 'PUT', body: new Uint8Array(body), headers: { 'content-type': 'image/jpeg' } });
  if (!put.ok) throw new Error(`PUT to the upload URL failed: ${put.status} ${await put.text()}`);
  return reserved.photo as { id: string; status: string; title: string | null; keywords: string[] };
}

