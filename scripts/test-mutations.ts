interface GqlError {
  message: string;
  extensions?: { code?: string };
}

interface RequestOptions {
  /** The API key to send; null sends none. Defaults to the run's key. */
  key?: string | null;
  /** Claimed client address, trusted by a server on loopback. */
  ip?: string;
}

async function request<T = any>(
  query: string,
  variables: Record<string, unknown> = {},
  token?: string,
  { key = apiKey, ip }: RequestOptions = {},
): Promise<{ status: number; headers: Headers; body: { data: T | null; errors?: GqlError[] } }> {
  const res = await fetch(API_URL, {
    method: 'POST',
    headers: {
      'content-type': 'application/json',
      ...(token ? { authorization: `Bearer ${token}` } : {}),
      ...(key ? { 'x-api-key': key } : {}),
      ...(ip ? { 'x-forwarded-for': ip } : {}),
    },
    body: JSON.stringify({ query, variables }),
  });
  return { status: res.status, headers: res.headers, body: (await res.json()) as { data: T | null; errors?: GqlError[] } };
}

async function gql<T = any>(
  query: string,
  variables: Record<string, unknown> = {},
  token?: string,
  options?: RequestOptions,
): Promise<{ data: T | null; errors?: GqlError[] }> {
  return (await request<T>(query, variables, token, options)).body;
}

/** Data, or throw on any GraphQL error. */
async function ok<T = any>(query: string, variables: Record<string, unknown> = {}, token?: string): Promise<T> {
  const { data, errors } = await gql<T>(query, variables, token);
  if (errors?.length) throw new Error(`GraphQL error: ${errors.map((e) => `${e.extensions?.code}: ${e.message}`).join('; ')}`);
  return data as T;
}

const globalId = (type: string, id: string) => Buffer.from(`${type}:${id}`).toString('base64');

